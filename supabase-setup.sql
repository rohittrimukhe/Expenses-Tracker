create or replace function is_admin()
returns boolean
language sql
stable
set search_path = public
as $$
  select auth.uid() = '2fd80b0e-3987-43e6-8669-d5d197876d14'::uuid;
$$;
revoke all on function is_admin() from public;
revoke all on function is_admin() from anon;
