-- The only place auth.users is read from — gated on is_admin() inside the
-- query itself, so a non-admin caller always gets zero rows back instead
-- of an error that might otherwise hint the function exists. security
-- definer is required here (reading auth.users needs elevated privilege);
-- the Advisor's "authenticated can call a security definer function"
-- warning is expected and accepted, same as it already is for the usage-
-- stats functions below — the internal is_admin() check is the real gate.
create or replace function list_users_for_admin()
returns table(id uuid, email text)
language sql
security definer
set search_path = public
stable
as $$
  select au.id, au.email::text
  from auth.users au
  where (select is_admin())
  order by au.created_at;
$$;
revoke all on function list_users_for_admin() from public;
revoke all on function list_users_for_admin() from anon;
grant execute on function list_users_for_admin() to authenticated;

